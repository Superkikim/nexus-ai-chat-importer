    /**
     * Calculate total duplicates from file stats
     */
    private getTotalDuplicates(): number {
        if (!this.fileStats) return 0;

        let totalDuplicates = 0;
        this.fileStats.forEach((stats) => {
            totalDuplicates += stats.duplicates || 0;
        });
        return totalDuplicates;
    }

    /**
     * Every conversation number the plugin reports, resolved once.
     *
     * Two phases produce these counts. The archive analysis knows what the ZIPs
     * held and what it decided to do; the vault writes know what actually
     * landed. The mobile flow (handleImportAllMobileSequential) skips the
     * analysis entirely, so `analysisAvailable` is false there and the write
     * counters are the only truth — which is why the fallbacks below exist
     * rather than being a smell to remove. They live here, once, instead of
     * being re-decided at each render.
     */
    getConversationLedger(): ConversationLedger {
        const writes = this.getGlobalStats();
        const analysis = this.analysisInfo;

        return {
            analysisAvailable: analysis !== undefined,

            // Archive-side. Zero without an analysis phase; read them only
            // behind `analysisAvailable` so they never render as a real zero.
            totalFound: analysis?.totalConversationsFound ?? 0,
            uniqueKept: analysis?.uniqueConversationsKept ?? 0,
            unchanged: analysis?.conversationsUnchanged ?? 0,
            reprocessed: analysis?.conversationsReprocessed ?? 0,

            // Vault-side.
            created: writes.created,
            updated: writes.updated,
            recreated: writes.recreated,
            failed: writes.failed,
            empty: this.getIgnoredCount(),
            noChange: writes.skipped,

            // Resolved. On the mobile flow an unchanged conversation reaches
            // the processor and is recorded by addSkipped, so the write
            // counter carries the same meaning the analysis would have.
            selected:
                this.selection?.selected ??
                analysis?.uniqueConversationsKept ??
                writes.totalProcessed,
            notSelected: this.selection
                ? Math.max(0, this.selection.offered - this.selection.selected)
                : null,
            // A sum, not a choice: the two counters hold disjoint populations.
            // The analysis one counts conversations dropped before the import
            // ever saw them (a full import without a rebuild); the write one
            // counts those that reached the processor and produced nothing
            // (a selective import, where every existing conversation is
            // offered). Picking one made a selected-but-unchanged conversation
            // vanish from the report and broke its arithmetic.
            unchangedSkipped:
                (analysis?.conversationsDroppedUnchanged ?? 0) + writes.skipped,
            totalConversations:
                analysis?.uniqueConversationsKept ?? writes.totalProcessed,
            duplicates:
                analysis?.duplicatesRemoved ?? this.getTotalDuplicates(),
        };
    }

    /**
     * Get statistics for the completion dialog
     */
    getCompletionStats() {
        const ledger = this.getConversationLedger();
        const attachmentStats = this.getTotalAttachmentStats();

        return {
            totalFiles: this.fileSections.size,
            totalConversations: ledger.totalConversations,
            duplicates: ledger.duplicates,
            created: ledger.created,
            updated: ledger.updated,
            recreated: ledger.recreated,
            unchanged: ledger.unchangedSkipped,
            notSelected: ledger.notSelected,
            emptyConversations: ledger.empty,
            failed: ledger.failed,
            attachmentsFound: attachmentStats.found,
            attachmentsTotal: attachmentStats.total,
            attachmentsMissing: attachmentStats.missing,
            attachmentsFailed: attachmentStats.failed,
        };
    }

